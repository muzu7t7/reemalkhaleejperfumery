export const aed = (n) => {
  const ar = getLang() === 'ar';
  const num = new Intl.NumberFormat(ar ? 'ar-AE-u-nu-latn' : 'en-AE', {
    minimumFractionDigits: Number.isInteger(n) ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(n);
  return ar ? `${num} د.إ` : `AED ${num}`;
};

